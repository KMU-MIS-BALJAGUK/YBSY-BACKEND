CREATE TABLE plans (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    user_id BIGINT NOT NULL,
    semester_id BIGINT NOT NULL,
    title VARCHAR(30) NOT NULL CHECK (CHAR_LENGTH(TRIM(title)) BETWEEN 1 AND 30),
    type VARCHAR(16) NOT NULL CHECK (type IN ('class','activity','project','custom')),
    credits INT CHECK (credits BETWEEN 1 AND 12),
    load_level VARCHAR(16) NOT NULL CHECK (load_level IN ('low','normal','high','custom')),
    start_week INT NOT NULL CHECK (start_week BETWEEN 1 AND 16),
    end_week INT NOT NULL CHECK (end_week BETWEEN 1 AND 16),
    hours_per_week DECIMAL(4,1) NOT NULL CHECK (hours_per_week BETWEEN 0.5 AND 60 AND MOD(hours_per_week, 0.5) = 0),
    start_date DATE,
    end_date DATE,
    priority VARCHAR(16) NOT NULL CHECK (priority IN ('low','normal','high')),
    category_id BIGINT,
    no_exam BOOLEAN NOT NULL,
    exam_only VARCHAR(16),
    study_days_mask INT CHECK (study_days_mask BETWEEN 1 AND 127),
    stopped_at DATETIME(6),
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    CHECK (start_week <= end_week),
    CHECK (start_date <= end_date),
    CHECK ((type = 'class') = (credits IS NOT NULL)),
    CHECK (NOT no_exam OR type = 'class'),
    CHECK (exam_only IS NULL OR (exam_only IN ('midterm','final') AND type = 'class' AND NOT no_exam)),
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (semester_id, user_id) REFERENCES semesters(id, user_id) ON DELETE CASCADE,
    FOREIGN KEY (category_id) REFERENCES plan_categories(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
